type Draft = {
  value?: number
  unit: string
  scope: CatalogValueScope
  limitType: LimitType
  conditions: Record<string, string>
  status: CatalogValueStatus
  caps?: CatalogValueCap
  note?: string
}

function docs(id: string): string {
  const entry = catalogEntries.find((item) => item.id === id)
  if (!entry) throw new Error(`catalog entry missing: ${id}`)
  return entry.docsUrl
}

function rows(id: string, drafts: Draft[], retrievedOn: string = catalogReadOn): CatalogValue[] {
  const sourceUrl = docs(id)
  return drafts.map((draft) => ({ ...draft, sourceUrl, retrievedOn }))
}

function unknown(metric: string, note: string, scope: CatalogValueScope = 'service'): Draft {
  return {
    unit: 'count',
    scope,
    limitType: 'quota_adjustability_unknown',
    conditions: { metric },
    status: 'unknown',
    note,
  }
}

/** A figure quoted from a supplied official page. No engine cap is attached. */
function pageFigure(
  metric: string,
  value: number | undefined,
  unit: string,
  scope: CatalogValueScope,
  limitType: LimitType,
  note: string,
  extra: Record<string, string> = {},
): Draft {
  return {
    ...(value === undefined ? {} : { value }),
    unit,
    scope,
    limitType,
    conditions: { metric, ...extra },
    status: value === undefined && limitType !== 'documented_behavior' ? 'unknown' : 'documented',
    note,
  }
}

function pgSku(
  sku: string,
  tier: string,
  maxConn: number,
  userConn: number,
  vCores: number,
  memoryGiB: number,
): Draft[] {
  return [
    pageFigure(
      'max-connections',
      maxConn,
      'count',
      'service',
      'configurable_setting',
      `Default max_connections for ${sku} (${vCores} vCores, ${memoryGiB} GiB). Set when the instance is provisioned; a later compute change does not update this default. The hardware maximum cannot be changed. max_connections can be adjusted and needs a restart. The page advises against raising it. Not wired as server count.`,
      { sku, tier, stated: sku },
    ),
    pageFigure(
      'max-user-connections',
      userConn,
      'count',
      'service',
      'configurable_setting',
      `Default maximum user connections for ${sku}: total minus 15 reserved. Reserved slots presently 15 and can change.`,
      { sku, tier, stated: sku },
    ),
  ]
}

/** AWS Batch service quotas page: unchanged, and each quota is Region specific. */
function batchQuota(
  metric: string,
  value: number,
  unit: string,
  note: string,
  extra: Record<string, string> = {},
): Draft {
  return {
    value,
    unit,
    scope: 'region',
    limitType: 'hard_limit',
    conditions: { metric, ...extra },
    status: 'documented',
    note: `${note} Unchanged quota. Each quota is Region specific. Not applied as worker throughput or server count.`,
  }
}

